function zad_seed_tile_page() {
	if ( ! current_user_can( 'manage_options' ) ) { return; }
	echo '<div class="wrap" dir="rtl"><h1>إنشاء صفحة ركيزة الجلي</h1>';
	$types = array_filter( zad_service_types(), function ( $t ) { $o = get_post_type_object( $t ); return $o && $o->hierarchical; } );
	$tgt   = in_array( 'cleaning', $types, true ) ? 'cleaning' : reset( $types );
	if ( ! $tgt ) { echo '<p>لا يوجد نوع محتوى هرمي للخدمات.</p></div>'; return; }

	if ( isset( $_POST['zad_seed_tile'] ) && check_admin_referer( 'zad_seed_tile' ) ) {
		$d    = zad_seed_tile_data();
		$have = get_posts( array( 'post_type' => $tgt, 'name' => $d['slug'], 'post_status' => 'any', 'numberposts' => 1 ) );
		if ( $have ) {
			echo '<div class="notice notice-warning"><p>توجد صفحة بالاسم نفسه: <a href="' . esc_url( get_edit_post_link( $have[0]->ID ) ) . '">افتحها</a>. لم أستبدل شيئاً.</p></div>';
		} else {
			$id = wp_insert_post( array( 'post_type' => $tgt, 'post_status' => 'draft', 'post_title' => $d['title'], 'post_name' => $d['slug'], 'post_content' => $d['content'], 'post_excerpt' => $d['excerpt'] ), true );
			if ( is_wp_error( $id ) ) {
				echo '<div class="notice notice-error"><p>' . esc_html( $id->get_error_message() ) . '</p></div>';
			} else {
				foreach ( $d['text'] as $k => $v ) { update_post_meta( $id, '_zad_' . $k, $v ); }
				foreach ( $d['rows'] as $k => $v ) { update_post_meta( $id, '_zad_' . $k, $v ); }
				update_post_meta( $id, '_zad_ix', $d['ix'] );
				update_post_meta( $id, '_zad_featured', '' );
				echo '<div class="notice notice-success"><p>أُنشئت المسودة. <a class="button button-primary" href="' . esc_url( get_edit_post_link( $id ) ) . '">تحرير</a> <a class="button" target="_blank" href="' . esc_url( get_preview_post_link( $id ) ) . '">معاينة</a></p></div>';
			}
		}
	}
	echo '<p>ينشئ مسودة واحدة (غير منشورة) في قسم «' . esc_html( get_post_type_object( $tgt )->labels->name ) . '» باسم <code>tile-polishing</code>، بمحتوى كامل وحقول الخدمة والأدوات التفاعلية. <strong>لا أسعار ولا أرقام ولا آراء مختلقة</strong>، وكل سطر عام ويجب مراجعته مع الفنيين قبل النشر. أضف صورة الغلاف وصور قبل/بعد والأسعار الحقيقية بعد ذلك.</p>';
	echo '<form method="post">';
	wp_nonce_field( 'zad_seed_tile' );
	echo '<p><button class="button button-primary" name="zad_seed_tile" value="1">إنشاء المسودة الآن</button></p></form></div>';
}
